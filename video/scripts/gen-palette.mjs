function extractThreeHexes(relPath) {
  const lines = read(relPath).split("\n");
  const seen = new Set();
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    for (const m of lines[i].matchAll(/(?:\b0x|#)([0-9a-fA-F]{6})\b/g)) {
      const hex = `#${m[1].toLowerCase()}`;
      if (!seen.has(hex)) {
        seen.add(hex);
        out.push({ value: hex, file: relPath, line: i + 1 });
      }
    }
  }
  return out;
}

