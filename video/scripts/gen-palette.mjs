const read = (p) => readFileSync(join(REPO, p), "utf8");

function findTokenInCss(relPath, varName) {
  const lines = read(relPath).split("\n");
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(new RegExp(`--${varName}:\\s*([^;]+);`));
    if (m) return { value: m[1].trim(), file: relPath, line: i + 1 };
  }
  throw new Error(`${relPath} missing --${varName}`);
}

function findHexInFile(relPath, hex) {
  const lines = read(relPath).split("\n");
  const lower = hex.toLowerCase();
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].toLowerCase().includes(lower)) {
      return { value: hex, file: relPath, line: i + 1 };
    }
  }
  throw new Error(`${relPath} no longer contains ${hex}`);
}

function extractHexArray(relPath, marker) {
  const text = read(relPath);
  const lines = text.split("\n");
  const idx = lines.findIndex((l) => l.includes(marker));
  if (idx < 0) throw new Error(`${relPath} missing ${marker}`);
  const slice = lines.slice(idx, idx + 40).join("\n");
  const hexes = [...slice.matchAll(/#[0-9a-fA-F]{6}/g)].map((m) => m[0].toLowerCase());
  if (hexes.length === 0) throw new Error(`No hexes found near ${marker} in ${relPath}`);
  return { values: [...new Set(hexes)], file: relPath, line: idx + 1 };
}

